#include "libft.h"

t_list	*ft_lstlast(t_list *lst)
{
	t_list	*node;

	node = lst;
	if (!lst)
		return (NULL);
	while (lst -> next)
		lst = lst -> next;
	node = lst;
	return (node);
}
